"""Generates the practice datasets used by the Data Science lessons.

Run: python3 scripts/generate_datasets.py  (stdlib only, deterministic)
Writes src/data/datasets/*.dataset.ts so the files can be loaded into the in-browser Python.
"""

import csv
import io
import random
from datetime import date, timedelta
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "data" / "datasets"
rng = random.Random(42)

MENU = {
    "Latte": ("Coffee", 75),
    "Americano": ("Coffee", 60),
    "Cappuccino": ("Coffee", 75),
    "Mocha": ("Coffee", 85),
    "Thai Tea": ("Tea", 55),
    "Green Tea": ("Tea", 50),
    "Croissant": ("Bakery", 65),
    "Banana Cake": ("Bakery", 70),
    "Cookie": ("Bakery", 35),
}
ITEM_WEIGHTS = [22, 14, 10, 6, 16, 8, 10, 6, 8]
BRANCHES = ["Downtown", "Riverside", "Campus"]
BRANCH_WEIGHTS = [45, 30, 25]
PAYMENTS = ["Card", "Cash", "QR"]


def sales_rows(n=240):
    start = date(2026, 1, 1)
    rows = []
    for i in range(n):
        day = start + timedelta(days=rng.randrange(90))
        item = rng.choices(list(MENU), ITEM_WEIGHTS)[0]
        category, price = MENU[item]
        branch = rng.choices(BRANCHES, BRANCH_WEIGHTS)[0]
        # Campus customers pay by QR more often; Downtown buys more per order.
        payment = rng.choices(PAYMENTS, [2, 2, 5] if branch == "Campus" else [4, 3, 3])[0]
        qty = rng.choices([1, 2, 3, 4], [55, 28, 12, 5] if branch != "Downtown" else [40, 32, 18, 10])[0]
        rows.append([1001 + i, day.isoformat(), branch, item, category, qty, price, payment])
    rows.sort(key=lambda r: (r[1], r[0]))
    for index, row in enumerate(rows):
        row[0] = 1001 + index
    return rows


def raw_rows(clean):
    rows = [list(r) for r in clean[:36]]
    rows[2][3:5] = [" latte", "Coffee"]
    rows[2][6] = 75
    rows[5][3:5] = ["LATTE", "Coffee"]
    rows[5][6] = 75
    rows[7][2] = "downtown"
    rows[9][5] = ""            # missing quantity
    rows[14][5] = ""
    rows[11][6] = ""           # missing price
    rows[18][5] = -2           # data-entry error
    rows[21][7] = ""           # missing payment
    rows[25][2] = "Riverside "
    rows.insert(12, list(rows[11]))   # exact duplicate
    rows.insert(30, list(rows[29]))
    return rows


def student_rows(n=40):
    names = ["Aung", "Su", "Kyaw", "Hnin", "Zaw", "Thiri", "Min", "Ei", "Htet", "Nandar",
             "Ko Ko", "May", "Phyo", "Yamin", "Naing", "Thida", "Wai", "Khin", "Tun", "Sandar"]
    rows = []
    for i in range(n):
        hours = round(rng.uniform(0.5, 10), 1)
        sleep = round(rng.uniform(4.5, 9), 1)
        attendance = rng.randint(55, 100)
        score = 28 + hours * 5.2 + (sleep - 6.5) * 2.5 + (attendance - 75) * 0.35 + rng.gauss(0, 6)
        score = max(5, min(100, round(score)))
        rows.append([f"{names[i % len(names)]} {chr(65 + i // len(names))}", hours, sleep, attendance, score,
                     "yes" if score >= 50 else "no"])
    return rows


def to_csv(header, rows):
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue()


def write_ts(name, filename, description, content):
    escaped = content.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    (OUT / f"{name}.dataset.ts").write_text(
        "// Generated by scripts/generate_datasets.py — do not edit by hand.\n"
        "import type { Dataset } from '@/models/dataset.model'\n\n"
        f"const dataset: Dataset = {{\n  filename: '{filename}',\n  description: '{description}',\n"
        f"  content: `{escaped}`\n}}\n\nexport default dataset\n"
    )


SALES_HEADER = ["order_id", "date", "branch", "item", "category", "quantity", "unit_price", "payment"]
clean = sales_rows()
write_ts("cafeSales", "cafe_sales.csv", "240 orders from 3 café branches, Jan–Mar 2026",
         to_csv(SALES_HEADER, clean))
write_ts("cafeSalesRaw", "cafe_sales_raw.csv", "38 messy orders: missing values, duplicates, typos",
         to_csv(SALES_HEADER, raw_rows(clean)))
write_ts("students", "students.csv", "40 students: study hours, sleep, attendance and exam score",
         to_csv(["student", "hours_studied", "sleep_hours", "attendance_pct", "score", "passed"], student_rows()))
print("written to", OUT)
